export function resolveSeoForPath(pathname) {
  const path = pathname.replace(/\/+$/, '') || '/';
  const canonicalPath = LEGACY_PATH_ALIASES[path] || path;

  if (SEO_BY_PATH[canonicalPath]) {
    return {
      ...DEFAULT_SEO,
      ...SEO_BY_PATH[canonicalPath],
      path: canonicalPath,
    };
  }

  const prefixMatch = SEO_BY_PREFIX.find((entry) =>
    canonicalPath.startsWith(entry.prefix)
  );
  if (prefixMatch) {
    return {
      ...DEFAULT_SEO,
      ...prefixMatch.seo,
      path: canonicalPath,
    };
  }

  return {
    ...DEFAULT_SEO,
    title: 'Page Not Found | DGMTS',
    description: 'The requested page could not be found on the DGMTS website.',
    path: canonicalPath,
    noIndex: true,
  };
}
